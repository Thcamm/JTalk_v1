/**
 * Kiểm tra xem một chuỗi có phải là tiếng Anh hay không (không có dấu tiếng Việt)
 */
export function isEnglishText(text) {
  if (!text || typeof text !== "string") return false;
  const trimmed = text.trim();
  if (!trimmed) return false;

  // Nếu có ký tự dấu tiếng Việt -> Không phải tiếng Anh
  const hasVietnameseAccent = /[àáạảãâầấậẩẫăằắặẳẵèéẹẻẽêềếệểễìíịỉĩòóọỏõôồốộổỗơờớợởỡùúụủũưừứựửữỳýỵỷỹđĐ]/i.test(
    trimmed
  );
  if (hasVietnameseAccent) return false;

  // Nếu toàn bộ là chữ cái Latin/dấu câu thông thường và chứa các từ chỉ thị tiếng Anh
  const lower = trimmed.toLowerCase();
  const englishKeywords = [
    "to ",
    "sleep",
    "eat",
    "drink",
    "go",
    "come",
    "see",
    "watch",
    "listen",
    "read",
    "write",
    "book",
    "water",
    "morning",
    "night",
    "school",
    "teacher",
    "student",
    "friend",
    "house",
    "room",
    "good",
    "bad",
    "big",
    "small",
    "hot",
    "cold",
    "walk",
    "run",
    "ride",
    "buy",
    "wait",
    "meet",
  ];

  return (
    englishKeywords.some((w) => lower.includes(w)) ||
    /^[a-zA-Z0-9\s,;.\-()/'"]+$/.test(trimmed)
  );
}

/**
 * Tự động chuyển đổi nghĩa tiếng Anh hoặc từ tiếng Nhật sang tiếng Việt chuẩn xác
 */
export function translateToVietnamese(kanji, rawMeaning) {
  const cleanKanji = (kanji || "").trim();
  const cleanMeaning = (rawMeaning || "").trim();

  // 1. Ưu tiên tra cứu từ tiếng Nhật trước
  if (cleanKanji && JAPANESE_TO_VIETNAMESE[cleanKanji]) {
    return JAPANESE_TO_VIETNAMESE[cleanKanji];
  }

  // 1b. Tra cứu tiếng Nhật bỏ tiền tố kính ngữ お hoặc ご
  if (cleanKanji) {
    const withoutHonorific = cleanKanji.replace(/^[おご]/, "");
    if (withoutHonorific && JAPANESE_TO_VIETNAMESE[withoutHonorific]) {
      return JAPANESE_TO_VIETNAMESE[withoutHonorific];
    }
    const withO = "お" + cleanKanji;
    if (JAPANESE_TO_VIETNAMESE[withO]) {
      return JAPANESE_TO_VIETNAMESE[withO];
    }
  }

  // 2. Tra cứu nghĩa tiếng Anh trực tiếp
  const lowerMeaning = cleanMeaning.toLowerCase();
  if (ENGLISH_TO_VIETNAMESE[lowerMeaning]) {
    return ENGLISH_TO_VIETNAMESE[lowerMeaning];
  }

  // 3. Tra cứu sau khi bỏ ngoặc giải thích (e.g. "lunch (midday meal)" -> "lunch")
  const strippedMeaning = lowerMeaning
    .replace(/\s*\([^)]*\)/g, "")
    .replace(/\s*\[[^\]]*\]/g, "")
    .replace(/^["']|["']$/g, "")
    .trim();
  if (strippedMeaning && ENGLISH_TO_VIETNAMESE[strippedMeaning]) {
    return ENGLISH_TO_VIETNAMESE[strippedMeaning];
  }

  // 4. Chuẩn hóa động từ có / không có "to "
  const withoutTo = strippedMeaning.replace(/^to\s+/, "").trim();
  if (withoutTo && ENGLISH_TO_VIETNAMESE[withoutTo]) {
    return ENGLISH_TO_VIETNAMESE[withoutTo];
  }
  const withTo = "to " + withoutTo;
  if (ENGLISH_TO_VIETNAMESE[withTo]) {
    return ENGLISH_TO_VIETNAMESE[withTo];
  }

  // 5. Tìm kiếm từng phần phân cách bởi dấu phẩy, chấm phẩy, gạch chéo
  const parts = lowerMeaning.split(/[,;/|]\s*/);
  for (const rawP of parts) {
    const p = rawP.replace(/\s*\([^)]*\)/g, "").replace(/^["']|["']$/g, "").trim();
    if (!p) continue;
    if (ENGLISH_TO_VIETNAMESE[p]) {
      return ENGLISH_TO_VIETNAMESE[p];
    }
    const pNoTo = p.replace(/^to\s+/, "");
    if (ENGLISH_TO_VIETNAMESE[pNoTo]) {
      return ENGLISH_TO_VIETNAMESE[pNoTo];
    }
  }

  // 6. Heuristic thông minh theo Kanji thông dụng nếu nghĩa gốc vẫn là tiếng Anh
  if (cleanKanji) {
    if (cleanKanji === "良" || cleanKanji === "良い" || cleanKanji === "よい" || cleanKanji === "いい") {
      return "Tốt, đẹp";
    }
    if (cleanKanji.includes("昼") && (cleanKanji.includes("飯") || cleanKanji.includes("食") || cleanKanji.includes("ごはん"))) {
      return "Bữa trưa, cơm trưa";
    }
    if (cleanKanji.includes("朝") && (cleanKanji.includes("飯") || cleanKanji.includes("食") || cleanKanji.includes("ごはん"))) {
      return "Bữa sáng, cơm sáng";
    }
    if ((cleanKanji.includes("晩") || cleanKanji.includes("夕") || cleanKanji.includes("夜")) && (cleanKanji.includes("飯") || cleanKanji.includes("食") || cleanKanji.includes("ごはん"))) {
      return "Bữa tối, cơm tối";
    }
    if (cleanKanji.includes("一") && cleanKanji.includes("人")) {
      return "Một mình, một người";
    }
    if (cleanKanji.includes("二") && cleanKanji.includes("人")) {
      return "Hai người";
    }
    if (cleanKanji.includes("信") && cleanKanji.includes("用")) {
      return "Tin tưởng, tín nhiệm";
    }
    if (cleanKanji.includes("信") && cleanKanji.includes("じ")) {
      return "Tin tưởng";
    }
  }

  // 7. Nếu nghĩa vốn dĩ đã là tiếng Việt thì giữ nguyên
  if (!isEnglishText(cleanMeaning)) {
    return cleanMeaning;
  }

  return cleanMeaning;
}

/**
 * Tự động tạo câu dịch ví dụ tiếng Việt tự nhiên, tránh bị lặp tiếng Anh
 */
export function sanitizeExampleTranslation(kanji, vietnameseMeaning, rawExampleTrans) {
  if (!rawExampleTrans || isEnglishText(rawExampleTrans) || rawExampleTrans.includes("to sleep")) {
    return `Thực hành ${vietnameseMeaning} bằng tiếng Nhật.`;
  }
  return rawExampleTrans;
}
